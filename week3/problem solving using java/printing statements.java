public class printing
{
    public static void main(String[]args)
    {
        System.out.println("hello");
        System.out.print("welcome");

         System.out.println("welcome\b\bhai");
         System.out.println("hi\b\bhai");

         System.out.println("welcome\thai");
         System.out.println("welcome\rhai");
         
        
        
        System.out.printf("%d",10);
        System.out.printf("%c",'a');
        System.out.printf("%C",'a');
        System.out.printf("%s","good");
        System.out.printf("%S","good");
        System.out.printf("%f",10.234);
        System.out.printf("%e",10.234);
        
    }
}
